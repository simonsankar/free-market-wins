import { defineConfig } from "astro/config"
import tailwindcss from "@tailwindcss/vite"
import { remarkVaultLinks } from "./src/lib/remark-vault-links.mjs"

export default defineConfig({
  site: "https://free-market-wins.up.railway.app",
  markdown: {
    remarkPlugins: [remarkVaultLinks],
  },
  vite: {
    plugins: [tailwindcss()],
    server: {
      watch: {
        // Content collections load from the vault root (one level above this
        // project), which makes Astro's content-layer watcher watch that
        // whole tree — including this very project's own node_modules/.astro
        // /dist. Combined with a picomatch quirk where mixed positive+negated
        // glob arrays match far more than intended, changes to our own build
        // artifacts were being fed back in as bogus "content entries" and
        // crashing the dev server. Ignoring them here stops the events at
        // the source, before that matching logic ever runs.
        ignored: ["**/site/node_modules/**", "**/site/.astro/**", "**/site/dist/**"],
      },
    },
    build: {
      // /pagefind/pagefind.js is generated by the Pagefind CLI *after*
      // `astro build` runs (see package.json), so it doesn't exist yet for
      // Rollup to resolve at bundle time — it's only ever imported at
      // runtime via a real browser fetch.
      rollupOptions: {
        external: ["/pagefind/pagefind.js"],
      },
    },
  },
})
